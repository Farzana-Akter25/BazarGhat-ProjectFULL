import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import * as XLSX from "xlsx";
import { formatDate, formatDateTime } from "./formatDate";

// same brand identity the admin sidebar, invoice modal and invoice PDF use
const SHOP_NAME = "BazarGhat";
const SHOP_TAGLINE = "Grocery & Organic E-commerce System";
const BRAND_COLOR = [255, 122, 0]; // #ff7a00
const HEADING_COLOR = [30, 30, 30];
const MUTED_COLOR = [120, 120, 120];


// Money and percentage formatters for the PDF
const pdfMoney = (n) => `Tk ${Number(n || 0).toLocaleString()}`;
const pdfSignedMoney = (n, sign) => `${sign} ${pdfMoney(Math.abs(Number(n || 0)))}`;
const pct = (n) => `${Number(n || 0).toFixed(1)}%`;

// Date range used in the downloaded file name
const fileStamp = (meta) => `${meta.startDate}_to_${meta.endDate}`;


// Only days that had orders, sales or refunds
const activeDays = (daily) =>
  (daily ?? []).filter((d) => d.orders > 0 || d.grossSales > 0 || d.refund > 0);

// PDF

// Draw the logo, shop name and report title at the top of the first page
function drawHeader(doc, meta) {
  doc.setFillColor(...BRAND_COLOR);
  doc.roundedRect(40, 32, 26, 26, 5, 5, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.text(SHOP_NAME[0], 53, 49, { align: "center" });

  doc.setTextColor(...BRAND_COLOR);
  doc.setFontSize(18);
  doc.text(SHOP_NAME, 74, 45);

  doc.setTextColor(...MUTED_COLOR);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.text(SHOP_TAGLINE, 74, 56);

  // Report type and number on the right
  const right = doc.internal.pageSize.getWidth() - 40;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.setTextColor(...HEADING_COLOR);
  doc.text(meta.reportType, right, 45, { align: "right" });
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(...MUTED_COLOR);
  doc.text(`Report No: ${meta.reportNumber}`, right, 58, { align: "right" });
}


// Print a section heading, starting a new page if there is not enough room
function sectionTitle(doc, title, y) {
  if (y > doc.internal.pageSize.getHeight() - 120) {
    doc.addPage();
    y = 60;
  }
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.setTextColor(...HEADING_COLOR);
  doc.text(title, 40, y);
  return y + 8;
}

// Runs a table and hands back the y to carry on from.
function table(doc, startY, head, body, options = {}) {
  // Kept out of the spread below so a section's own hook adds to this one instead of replacing it.
  const { didParseCell: sectionHook, ...rest } = options;

  autoTable(doc, {
    startY,
    margin: { left: 40, right: 40 },
    head,
    body: body.length ? body : [[{ content: "No data for this period", colSpan: head[0].length }]],
    headStyles: { fillColor: BRAND_COLOR, textColor: 255, fontSize: 8.5 },
    styles: { fontSize: 8.5, cellPadding: 4, overflow: "linebreak" },

    rowPageBreak: "avoid",
    ...rest,
    didParseCell: (data) => {
      // A heading has to sit over its own figures: the header cell takes whatever alignment the
      // column's values were given, so "Amount" lands above the amounts instead of off to the left.
      if (data.section === "head") {
        // Alignment given to this column's values
        const valueAlign = options.columnStyles?.[data.column.index]?.halign;

        if (valueAlign) {
          data.cell.styles.halign = valueAlign;
        }
      }

      sectionHook?.(data);
    },
  });

  return doc.lastAutoTable.finalY + 22;
}

// Draw the footer (brand, generated-by and page number) on every page
function drawFooter(doc, meta) {
  // Page count and page size
  const pages = doc.internal.getNumberOfPages();
  const width = doc.internal.pageSize.getWidth();
  const height = doc.internal.pageSize.getHeight();

  // Loop over every page
  for (let page = 1; page <= pages; page += 1) {
    doc.setPage(page);
    doc.setDrawColor(230, 230, 230);
    doc.setLineWidth(0.5);
    doc.line(40, height - 52, width - 40, height - 52);

    doc.setFont("helvetica", "bold");
    doc.setFontSize(8);
    doc.setTextColor(...BRAND_COLOR);
    doc.text(SHOP_NAME, 40, height - 38);

    doc.setFont("helvetica", "normal");
    doc.setTextColor(...MUTED_COLOR);
    doc.text(SHOP_TAGLINE, 40, height - 28);
    doc.text("This report is generated from the BazarGhat system records.", 40, height - 18);

    doc.text(
      `Generated by ${meta.generatedBy} · ${formatDate(meta.generatedAt)}`,
      width - 40,
      height - 28,
      { align: "right" },
    );
    doc.text(`Page ${page} of ${pages}`, width - 40, height - 18, { align: "right" });
  }
}

// Build the full business report as a PDF and download it
export function downloadBusinessReportPdf(report) {
  // All sections of the report data
  const {
    meta, sales, summary, orders, payments, products, categories,
    coupons, returns: returnStats, wallet, delivery, customers, inventory,
    dailySales, kpis,
  } = report;

  // New A4 document with the header drawn
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  drawHeader(doc, meta);

  // Current vertical position on the page
  let y = 86;

  // 1.
  y = sectionTitle(doc, "Report Information", y);
  y = table(
    doc,
    y,
    [["Field", "Value"]],
    [
      ["Report No", meta.reportNumber],
      ["Report Type", meta.reportType],
      ["Period", `${formatDate(meta.startDate)} to ${formatDate(meta.endDate)} (${meta.dayCount} days)`],
      ["Generated Date", formatDateTime(meta.generatedAt)],
      ["Generated By", meta.generatedBy],
    ],
    { columnStyles: { 0: { cellWidth: 130, fontStyle: "bold" } } },
  );

  // 2.
  y = sectionTitle(doc, "Executive Summary", y);
  y = table(
    doc,
    y,
    [["Sales", "Amount", "Orders", "Count", "Performance", "Value"]],
    [
      ["Gross Product Sales", pdfMoney(sales.grossProductSales), "Total Orders", String(summary.orders.total), "Completion Rate", pct(kpis.completionRate)],
      ["Total Discount", pdfSignedMoney(sales.totalDiscount, "-"), "Delivered", String(summary.orders.delivered), "Cancellation Rate", pct(kpis.cancellationRate)],
      ["Delivery Fee", pdfSignedMoney(sales.deliveryFee, "+"), "Cancelled", String(summary.orders.cancelled), "Return Rate", pct(kpis.returnRate)],
      ["Total Refund", pdfSignedMoney(sales.totalRefund, "-"), "Returned", String(summary.orders.returned), "Avg Order Value", pdfMoney(kpis.averageOrderValue)],
      ["Net Sales", pdfMoney(sales.netSales), "Pending", String(summary.orders.pending), "Units Sold", String(summary.products.unitsSold)],
      ["Customers Ordered", String(summary.customers.ordered), "New Customers", String(summary.customers.new), "Returning", String(summary.customers.returning)],
    ],
    {
      columnStyles: {
        1: { halign: "right" }, 3: { halign: "right" }, 5: { halign: "right" },
      },
      didParseCell: (data) => {
        // the net sales line is the one figure the whole section builds to
        if (data.section === "body" && data.row.index === 4 && data.column.index <= 1) {
          data.cell.styles.fontStyle = "bold";
        }
      },
    },
  );

  // 3.
  y = sectionTitle(doc, "Sales Summary", y);
  y = table(
    doc,
    y,
    [["Sales Details", "Amount"]],
    [
      ["Gross Product Sales", pdfMoney(sales.grossProductSales)],
      ["Total Discount", pdfSignedMoney(sales.totalDiscount, "-")],
      ["Delivery Fee", pdfSignedMoney(sales.deliveryFee, "+")],
      ["Total Refund", pdfSignedMoney(sales.totalRefund, "-")],
      ["NET SALES", pdfMoney(sales.netSales)],
    ],
    {
      columnStyles: { 0: { cellWidth: 300 }, 1: { halign: "right" } },
      didParseCell: (data) => {
        if (data.section === "body" && data.row.index === 4) {
          data.cell.styles.fontStyle = "bold";
          data.cell.styles.fillColor = [255, 244, 232];
        }
      },
    },
  );

  // 4.
  y = sectionTitle(doc, "Order Summary", y);
  y = table(
    doc,
    y,
    [["Order Status", "Orders", "Amount", "Percentage"]],
    orders.rows.map((row) => [row.status, String(row.orders), pdfMoney(row.amount), pct(row.percentage)]),
    { columnStyles: { 1: { halign: "right" }, 2: { halign: "right" }, 3: { halign: "right" } } },
  );

  // 5.
  y = sectionTitle(doc, "Payment Summary", y);
  y = table(
    doc,
    y,
    [["Payment Method", "Orders", "Charged", "Collected", "Share"]],
    payments.rows.map((row) => [
      row.method, String(row.orders), pdfMoney(row.amount), pdfMoney(row.collected), pct(row.percentage),
    ]),
    {
      columnStyles: {
        1: { halign: "right" }, 2: { halign: "right" }, 3: { halign: "right" }, 4: { halign: "right" },
      },
    },
  );
  y = table(
    doc,
    y - 14,
    [["Payment Totals", "Amount"]],
    [
      ["Total Online Payment", pdfMoney(payments.totalOnline)],
      ["Total COD Payment", pdfMoney(payments.totalCod)],
      ["Total Wallet Payment", pdfMoney(payments.totalWallet)],
      ["Total Order Value", pdfMoney(payments.totalOrderValue)],
    ],
    { columnStyles: { 0: { cellWidth: 300 }, 1: { halign: "right" } } },
  );

  // 6.
  y = sectionTitle(doc, "Top Selling Products", y);
  y = table(
    doc,
    y,
    [["#", "Product", "Category", "Qty Sold", "Gross Sales", "Discount", "Net Sales"]],
    products.map((p) => [
      String(p.rank),
      p.unit ? `${p.product} (${p.unit})` : p.product,
      p.category,
      String(p.qtySold),
      pdfMoney(p.grossSales),
      pdfMoney(p.discount),
      pdfMoney(p.netSales),
    ]),
    {
      columnStyles: {
        0: { cellWidth: 24, halign: "center" },
        3: { halign: "right" }, 4: { halign: "right" }, 5: { halign: "right" }, 6: { halign: "right" },
      },
    },
  );

  // 7.
  y = sectionTitle(doc, "Category Performance", y);
  y = table(
    doc,
    y,
    [["Category", "Products", "Qty Sold", "Gross Sales", "Discount", "Net Sales", "Share"]],
    categories.map((c) => [
      c.category, String(c.productsSold), String(c.qtySold),
      pdfMoney(c.grossSales), pdfMoney(c.discount), pdfMoney(c.netSales), pct(c.percentage),
    ]),
    {
      columnStyles: {
        1: { halign: "right" }, 2: { halign: "right" }, 3: { halign: "right" },
        4: { halign: "right" }, 5: { halign: "right" }, 6: { halign: "right" },
      },
    },
  );

  // 8.
  y = sectionTitle(doc, "Coupon & Discount Summary", y);
  y = table(
    doc,
    y,
    [["Coupon", "Campaign", "Orders", "Discount", "Free Delivery"]],
    coupons.rows.map((c) => [
      c.code, c.campaign || "-", String(c.orders), pdfMoney(c.discount), String(c.freeDeliveryOrders),
    ]),
    { columnStyles: { 2: { halign: "right" }, 3: { halign: "right" }, 4: { halign: "right" } } },
  );
  y = table(
    doc,
    y - 14,
    [["Coupon Totals", "Value"]],
    [
      ["Orders Using a Coupon", String(coupons.ordersWithCoupon)],
      ["Total Coupon Discount", pdfMoney(coupons.totalDiscount)],
      ["Free Delivery Orders", String(coupons.freeDeliveryOrders)],
      ["Customer-Specific Coupon Usage", String(coupons.customerSpecificUsage)],
      ["General Coupon Usage", String(coupons.generalUsage)],
    ],
    { columnStyles: { 0: { cellWidth: 300 }, 1: { halign: "right" } } },
  );

  // 9.
  y = sectionTitle(doc, "Return & Refund Summary", y);
  y = table(
    doc,
    y,
    [["Return / Refund", "Value"]],
    [
      ["Total Return Requests", String(returnStats.totalRequests)],
      ["Pending", String(returnStats.pending)],
      ["In Review", String(returnStats.inReview)],
      ["Approved", String(returnStats.approved)],
      ["Rejected", String(returnStats.rejected)],
      ["Completed", String(returnStats.completed)],
      ["Refunds Completed", String(returnStats.refundCount)],
      ["SSLCommerz Refund", pdfMoney(returnStats.gatewayRefund)],
      ["Wallet Refund", pdfMoney(returnStats.walletRefund)],
      ["Total Refund Amount", pdfMoney(returnStats.totalRefundAmount)],
    ],
    { columnStyles: { 0: { cellWidth: 300 }, 1: { halign: "right" } } },
  );

  // 10.
  y = sectionTitle(doc, "Wallet Summary", y);
  y = table(
    doc,
    y,
    [["Wallet", "Amount"]],
    [
      ["Total Wallet Used on Orders", pdfMoney(wallet.totalWalletUsed)],
      ["Total Wallet Refund", pdfMoney(wallet.totalWalletRefund)],
      ["Total Wallet Credit", pdfMoney(wallet.totalCredit)],
      ["Total Wallet Deduction", pdfMoney(wallet.totalDebit)],
    ],
    { columnStyles: { 0: { cellWidth: 300 }, 1: { halign: "right" } } },
  );

  // 11.
  y = sectionTitle(doc, "Delivery Performance", y);
  y = table(
    doc,
    y,
    [["Delivery", "Count"]],
    [
      ["Total Assigned", String(delivery.totalAssigned)],
      ["Accepted", String(delivery.accepted)],
      ["Picked Up", String(delivery.pickedUp)],
      ["On the Way", String(delivery.onTheWay)],
      ["Delivered", String(delivery.delivered)],
      ["Pending", String(delivery.pending)],
      ["Delivery Issues", String(delivery.issues)],
      ["Delivery Earnings", `${pdfMoney(delivery.earnings.total)} (${pdfMoney(delivery.earnings.perOrder)} x ${delivery.earnings.deliveredOrders})`],
    ],
    { columnStyles: { 0: { cellWidth: 300 }, 1: { halign: "right" } } },
  );
  if (delivery.riders.length) {
    y = table(
      doc,
      y - 14,
      [["Delivery Person", "Assigned", "Accepted", "Delivered", "Pending"]],
      delivery.riders.map((r) => [
        r.name, String(r.assigned), String(r.accepted), String(r.delivered), String(r.pending),
      ]),
      {
        columnStyles: {
          1: { halign: "right" }, 2: { halign: "right" }, 3: { halign: "right" }, 4: { halign: "right" },
        },
      },
    );
  }

  // 12.
  y = sectionTitle(doc, "Customer Summary", y);
  y = table(
    doc,
    y,
    [["Customers", "Value"]],
    [
      ["Customers Who Ordered", String(customers.ordered)],
      ["New Customers", String(customers.new)],
      ["Returning Customers", String(customers.returning)],
      ["Total Orders by Customers", String(customers.totalOrders)],
      ["Average Orders per Customer", String(customers.averageOrdersPerCustomer)],
    ],
    { columnStyles: { 0: { cellWidth: 300 }, 1: { halign: "right" } } },
  );
  if (customers.topCustomers.length) {
    y = table(
      doc,
      y - 14,
      [["Top Customer", "Orders", "Order Value"]],
      customers.topCustomers.map((c) => [c.name, String(c.orders), pdfMoney(c.amount)]),
      { columnStyles: { 1: { halign: "right" }, 2: { halign: "right" } } },
    );
  }

  // 13.
  y = sectionTitle(doc, "Inventory Summary", y);
  y = table(
    doc,
    y,
    [["Inventory", "Count"]],
    [
      ["Total Products", String(inventory.totalProducts)],
      ["In Stock", String(inventory.inStock)],
      ["Low Stock", String(inventory.lowStock)],
      ["Out of Stock", String(inventory.outOfStock)],
    ],
    { columnStyles: { 0: { cellWidth: 300 }, 1: { halign: "right" } } },
  );
  // Low-stock and out-of-stock products in one list
  const stockWatch = [...inventory.lowStockProducts, ...inventory.outOfStockProducts];
  if (stockWatch.length) {
    y = table(
      doc,
      y - 14,
      [["Product", "Category", "Current Stock", "Stock Status"]],
      stockWatch.map((p) => [
        p.unit ? `${p.name} (${p.unit})` : p.name,
        p.category || "-",
        String(p.stock),
        p.status,
      ]),
      { columnStyles: { 2: { halign: "right" } } },
    );
  }

  // 14.
  y = sectionTitle(doc, "Daily Sales Breakdown", y);
  y = table(
    doc,
    y,
    [["Date", "Orders", "Gross Sales", "Discount", "Refund", "Net Sales"]],
    activeDays(dailySales).map((d) => [
      formatDate(d.date), String(d.orders), pdfMoney(d.grossSales),
      pdfMoney(d.discount), pdfMoney(d.refund), pdfMoney(d.netSales),
    ]),
    {
      columnStyles: {
        1: { halign: "right" }, 2: { halign: "right" }, 3: { halign: "right" },
        4: { halign: "right" }, 5: { halign: "right" },
      },
    },
  );

  // 15.
  y = sectionTitle(doc, "Final Financial Summary", y);
  table(
    doc,
    y,
    [["Final Summary", "Value"]],
    [
      ["Gross Product Sales", pdfMoney(sales.grossProductSales)],
      ["Total Discount", pdfSignedMoney(sales.totalDiscount, "-")],
      ["Delivery Fee", pdfSignedMoney(sales.deliveryFee, "+")],
      ["Total Refund", pdfSignedMoney(sales.totalRefund, "-")],
      ["NET SALES", pdfMoney(sales.netSales)],
      ["Total Orders", String(summary.orders.total)],
      ["Completed Orders", String(kpis.deliveredOrders)],
      ["Total Customers", String(customers.ordered)],
      ["Products Sold", String(summary.products.unitsSold)],
      ["Average Order Value", pdfMoney(kpis.averageOrderValue)],
    ],
    {
      columnStyles: { 0: { cellWidth: 300 }, 1: { halign: "right" } },
      didParseCell: (data) => {
        if (data.section === "body" && data.row.index === 4) {
          data.cell.styles.fontStyle = "bold";
          data.cell.styles.fillColor = [255, 244, 232];
        }
      },
    },
  );

  // Add footers to every page, then save the file
  drawFooter(doc, meta);
  doc.save(`BazarGhat-Report-${fileStamp(meta)}.pdf`);
}

